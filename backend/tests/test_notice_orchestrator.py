import pytest
from backend.notice_orchestrator import sanitize, validate_output, repair_output

BAD_TEXT = """
FORMAL NOTICE
---
Subject: Demand
§106 TPA (Verified Gazette)
You must pay SEVEN (7) DAYS.
---
Generated by AI. Not legal advice. Verify.
"""

def test_sanitize():
    res = sanitize(BAD_TEXT)
    assert "§" not in res.text
    assert "Verified Gazette" not in res.text
    assert "SEVEN (7) DAYS" not in res.text
    assert "Generated by" not in res.text
    assert "---" not in res.text
    assert "7 (seven) days" in res.text
    assert res.violations

def test_validate():
    good = """From: [Tenant]\nTo: [Landlord]\nSubject: Notice\nYours faithfully, [Name]\nBody here."""
    assert validate_output(good) == []
    bad = "No from"
    assert any("From" in e for e in validate_output(bad))


def test_orchestrate_notice():
    from backend.notice_orchestrator import orchestrate_notice
    from types import SimpleNamespace

    dummy_state = SimpleNamespace(
        case_type="deposit",
        tenant_name="Aarav Sharma",
        landlord_name="Ramesh Gupta",
        property_address="Flat 402, Koramangala, Bengaluru",
        pin_code="560034",
        monthly_rent=30000.0,
        deposit_paid=180000.0,
        deductions_claimed=40000.0,
        move_out_date="2026-10-01",
        itemised_bills_provided=False,
        analysis=None,
        arithmetic=None
    )

    notice = orchestrate_notice(dummy_state)
    assert notice.from_name == "Aarav Sharma"
    assert notice.to_name == "Ramesh Gupta"
    assert len(notice.body_paragraphs) >= 4
    # All paragraphs must be free from AI disclaimers and § symbols
    for p in notice.body_paragraphs:
        assert "§" not in p
        assert "Generated by AI" not in p
        assert "not legal advice" not in p.lower()
    assert "15 (fifteen) days" in notice.demand_text

