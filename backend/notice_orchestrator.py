"""Orchestrator enforcement layer for legal notice output.
Validates, sanitizes, and repairs LLM output before rendering.
"""
import re
from typing import List, Optional, Dict
from pydantic import BaseModel, Field, validator


class NoticeOutput(BaseModel):
    date: str = Field(..., description="Top date, format '30 October 2026'")
    from_name: str = "[TENANT NAME]"
    from_address: str = "[PROPERTY ADDRESS]"
    to_name: str = "[LANDLORD NAME]"
    to_address: str = "[PROPERTY ADDRESS]"
    subject: str = "Subject: Formal Demand Under Section 108(m) of the Transfer of Property Act, 1882"
    include_mode_line: bool = False
    body_paragraphs: List[str] = Field(default_factory=list)
    demand_text: str = "Within 7 (seven) days from receipt of this notice..."
    closing: str = "Yours faithfully,"
    signature_name: str = "[TENANT NAME]"


class SanitizeResult:
    def __init__(self, text: str, violations: List[str]):
        self.text = text
        self.violations = violations
    text: str
    violations: List[str]


def sanitize(text: str) -> SanitizeResult:
    violations = []
    # § symbol
    if "§" in text:
        violations.append("Contains § symbol")
        text = text.replace("§", "Section ").replace("§§", "Sections ")
    # Verified tags
    for m in re.finditer(r"\(\s*Verified[^)]*\)", text, re.IGNORECASE):
        violations.append(f"Verified tag: {m.group()}")
        text = text.replace(m.group(), "")
    # AI / disclaimer lines (any line containing any bad phrase)
    bad_phrases = ["generated by", "not legal advice", "verify with an advocate", "placeholder", "ai assistant"]
    lines = text.split("\n")
    cleaned_lines = []
    removed_phrases = []
    for line in lines:
        lower_line = line.lower()
        if any(bp in lower_line for bp in bad_phrases):
            removed_phrases.extend([bp for bp in bad_phrases if bp in lower_line])
        else:
            cleaned_lines.append(line)
    text = "\n".join(cleaned_lines)
    for p in set(removed_phrases):
        violations.append(f"Weakness phrase: {p}")
    # Divider lines only
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped and all(ch in "-=_*──" for ch in stripped):
            violations.append(f"Divider line: {stripped[:20]}")
            text = text.replace(line, "")
    # SEVEN (7) DAYS -> 7 (seven) days
    text = re.sub(r"\bSEVEN\s*\(7\)\s*DAYS\b", "7 (seven) days", text, flags=re.IGNORECASE)
    # Numbers
    text = re.sub(r"\b(\w+)\s*\((\d+)\)\s*DAYS\b", lambda m: f"{m.group(2)} ({_word_num(int(m.group(2)))}) days", text, flags=re.IGNORECASE)
    # Lowercase stray ALL-CAPS words in body (not Subject / From / To)
    return SanitizeResult(text=text, violations=violations)


def _word_num(n: int) -> str:
    mapping = {1:"one",2:"two",3:"three",4:"four",5:"five",6:"six",7:"seven",8:"eight",9:"nine",10:"ten"}
    return mapping.get(n, str(n))


def validate_output(text: str, include_mode_line: bool = False) -> List[str]:
    errors = []
    if "§" in text:
        errors.append("Remaining § symbol")
    if "Verified" in text and "Gazette" in text:
        errors.append("Remaining verification tag")
    if "Generated by" in text or "Not legal advice" in text or "AI assistant" in text.lower():
        errors.append("Remaining AI disclaimer")
    if "---" in text:
        errors.append("Remaining divider")
    # Must have From / To / Subject
    if "FROM:" not in text and "From:" not in text:
        errors.append("Missing From block")
    if "TO:" not in text and "To:" not in text:
        errors.append("Missing To block")
    if "SUBJECT:" not in text and "Subject:" not in text:
        errors.append("Missing Subject line")
    if "Yours faithfully" not in text and "Yours sincerely" not in text:
        errors.append("Missing closing 'Yours faithfully'")
    if include_mode_line and "MODE" not in text:
        errors.append("Missing Mode line when requested")
    if not include_mode_line and ("MODE:" in text or "Registered Post" in text):
        # Actually we allow mode if present; only flag if explicitly false and present? Skip strict.
        pass
    return errors


def repair_output(text: str, errors: List[str]) -> str:
    # One repair pass: tell LLM to fix only listed errors
    repair_prompt = (
        f"Fix ONLY these issues in the legal notice text below. Change nothing else.\n"
        f"Issues: {', '.join(errors)}\n\nText:\n{text}\n\nFixed text:"
    )
    # In real deployment this calls ChatGroq; here we simulate deterministic fix
    # For this harness, we apply regex fixes directly based on errors
    fixed = text
    for e in errors:
        if "§" in e:
            fixed = fixed.replace("§", "Section ")
        if "Verified" in e:
            fixed = re.sub(r"\(\s*Verified[^)]*\)", "", fixed, flags=re.IGNORECASE)
        if "AI" in e or "disclaimer" in e.lower() or "placeholder" in e.lower():
            fixed = re.sub(r"(?im)Generated by.*?before sending\.?", "", fixed)
            fixed = re.sub(r"(?im)Not legal advice\.?", "", fixed)
        if "divider" in e.lower():
            for line in fixed.split("\n"):
                if all(ch in "-=_*──" for ch in line.strip()):
                    fixed = fixed.replace(line, "")
    return fixed
