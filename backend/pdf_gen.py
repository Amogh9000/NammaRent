"""
ReportLab Demand Notice PDF Generator for Namma Tenant Navigator.
Renders legal demand notices grounded in Karnataka housing law with
vault re-insertion at render time, unverified source disclaimers,
and highlighted missing fields.
"""

from pathlib import Path
from datetime import datetime
from typing import Optional, List, Any
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.pdfgen import canvas

from backend.privacy import PrivacyEngine
from backend.retriever import KnowledgeBase


class NumberedCanvas(canvas.Canvas):
    """Adds formal running footer to every page."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#555555"))
        
        # Top Rule & Banner
        self.setStrokeColor(colors.HexColor("#D1D5DB"))
        self.setLineWidth(0.5)
        self.line(54, 750, 558, 750)
        self.drawString(54, 755, "NAMMA TENANT NAVIGATOR | LEGAL AID & DEMAND NOTICE")
        self.drawRightString(558, 755, f"PAGE {self._pageNumber} OF {page_count}")

        # Bottom Rule & Mandatory Legal Footer
        self.line(54, 45, 558, 45)
        footer_text = "Generated by an AI assistant. Not legal advice. Verify with an advocate before sending."
        self.drawString(54, 32, footer_text)
        self.drawRightString(558, 32, "BENGALURU URBAN JURISDICTION")
        self.restoreState()


def generate_demand_notice_pdf(state: Any, output_path: Path) -> Path:
    """Generates a professional legal demand notice PDF."""
    engine = PrivacyEngine.get_instance()
    kb = KnowledgeBase.get_instance()

    # Re-insert real details from local vault at render time
    raw_tenant = state.tenant_name or engine.unmask("[TENANT_NAME]", state.session_id)
    raw_landlord = state.landlord_name or engine.unmask("[LANDLORD_NAME]", state.session_id)
    raw_address = state.property_address or engine.unmask("[PROPERTY_ADDRESS]", state.session_id)
    pin = state.pin_code or ""

    tenant_name = raw_tenant if raw_tenant and raw_tenant != "[TENANT_NAME]" else "<font color='#DC2626'><b>[TENANT_NAME - MISSING]</b></font>"
    landlord_name = raw_landlord if raw_landlord and raw_landlord != "[LANDLORD_NAME]" else "<font color='#DC2626'><b>[LANDLORD_NAME - MISSING]</b></font>"
    address = raw_address if raw_address and raw_address != "[PROPERTY_ADDRESS]" else "<font color='#DC2626'><b>[PROPERTY_ADDRESS - MISSING]</b></font>"

    doc = SimpleDocTemplate(
        str(output_path),
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=60,
        bottomMargin=60
    )

    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=15,
        leading=18,
        alignment=1,  # Center
        textColor=colors.HexColor('#0F172A'),
        spaceAfter=4
    )

    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=12,
        alignment=1,
        textColor=colors.HexColor('#475569'),
        spaceAfter=14
    )

    meta_style = ParagraphStyle(
        'MetaStyle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=13,
        textColor=colors.HexColor('#1E293B')
    )

    bold_meta = ParagraphStyle(
        'BoldMeta',
        parent=meta_style,
        fontName='Helvetica-Bold'
    )

    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor('#1E293B'),
        spaceAfter=8
    )

    alert_style = ParagraphStyle(
        'WarningBox',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor('#B45309'),
        backColor=colors.HexColor('#FEF3C7'),
        borderColor=colors.HexColor('#F59E0B'),
        borderWidth=1,
        borderPadding=6,
        spaceAfter=10
    )

    elements = []

    # Title & Subtitle
    elements.append(Paragraph("FORMAL LEGAL DEMAND NOTICE", title_style))
    elements.append(Paragraph("ISSUED UNDER THE TRANSFER OF PROPERTY ACT, 1882 & KARNATAKA TENANCY REGULATIONS", subtitle_style))
    elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#0F172A"), spaceAfter=12))

    # Sender / Recipient / Date Table
    curr_date = datetime.now().strftime("%d %B %Y")
    parties_data = [
        [
            Paragraph(f"<b>FROM:</b><br/>{tenant_name}<br/>Former Tenant<br/>Bengaluru, Karnataka", meta_style),
            Paragraph(f"<b>TO:</b><br/>{landlord_name}<br/>Property Owner / Lessor<br/>Premises: {address}<br/>PIN: {pin}", meta_style)
        ],
        [
            Paragraph(f"<b>DATE:</b> {curr_date}", bold_meta),
            Paragraph("<b>MODE:</b> Registered Post A.D. / Formal Written Notice", bold_meta)
        ]
    ]

    parties_table = Table(parties_data, colWidths=[250, 250])
    parties_table.setStyle(TableStyle([
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 8),
    ]))
    elements.append(parties_table)
    elements.append(Spacer(1, 10))

    # Subject Line
    case_type = state.case_type or "deposit"
    if case_type == "deposit":
        subj = f"<b>SUBJECT: URGENT LEGAL DEMAND FOR REFUND OF UNLAWFULLY WITHHELD SECURITY DEPOSIT (₹{state.arithmetic.net_refundable_amount if state.arithmetic else state.deposit_paid:,.0f}) REGARDING PREMISES AT {address}</b>"
    else:
        subj = f"<b>SUBJECT: FORMAL WRITTEN OBJECTION TO UNLAWFUL RENT REVISION NOTICE REGARDING PREMISES AT {address}</b>"
    
    elements.append(Paragraph(subj, ParagraphStyle('Subj', parent=body_style, fontName='Helvetica-Bold', fontSize=10, leading=14)))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CBD5E1"), spaceAfter=10))

    # Unverified KB Warning Alert in PDF
    has_unverified = False
    if state.analysis and state.analysis.warning_unverified_sources:
        has_unverified = True
        uv_list = ", ".join(state.analysis.warning_unverified_sources)
        elements.append(Paragraph(
            f"<b>NOTICE OF VERIFICATION STATUS:</b> The legal authorities cited herein ({uv_list}) "
            "contain statutory placeholders awaiting certified gazette validation. While principles reflect established "
            "Karnataka tenancy jurisprudence, advocate verification is recommended before court filing.",
            alert_style
        ))

    # Salutation & Facts
    elements.append(Paragraph("Sir / Madam,", body_style))
    elements.append(Paragraph(
        "Under explicit instructions and on behalf of the tenant named above, the following demand is hereby formally served upon you:",
        body_style
    ))

    # Numbered Factual Recitals
    arith = state.arithmetic
    elements.append(Paragraph("<b>STATEMENT OF FACTS:</b>", bold_meta))
    
    facts = []
    if case_type == "deposit":
        facts.append(
            f"1. That the Tenant occupied the residential premises situated at {address} on an agreed monthly rent of ₹{state.monthly_rent:,.0f}/-."
        )
        facts.append(
            f"2. That at the commencement of the tenancy, the Tenant paid a total security deposit of ₹{state.deposit_paid:,.0f}/- ({arith.deposit_months if arith else 'N/A'} months of rent)."
        )
        facts.append(
            f"3. That the Tenant peacefully vacated and handed over vacant physical possession of the said premises on {state.move_out_date or 'the agreed handover date'} with all utility dues cleared."
        )
        deduction_sum = state.deductions_claimed or 0.0
        if deduction_sum > 0:
            facts.append(
                f"4. That you have unlawfully withheld the sum of ₹{deduction_sum:,.0f}/- citing arbitrary deductions ({state.deduction_reasons or 'painting / deep cleaning / wear & tear'}) without providing itemised, GST-compliant repair invoices."
            )
        else:
            facts.append(
                "4. That you have failed and neglected to refund the refundable security deposit despite vacant possession being duly handed over."
            )
    else:
        facts.append(
            f"1. That the Tenant occupies premises at {address} under an agreed monthly rent of ₹{state.current_rent:,.0f}/-."
        )
        facts.append(
            f"2. That on {state.notice_received_date or 'recent date'}, a communication was tendered proposing to enhance the rent to ₹{state.proposed_rent:,.0f}/- effective from {state.effective_date or 'immediate effect'}."
        )
        facts.append(
            f"3. That the notice period provided ({arith.notice_gap_days if arith else 'insufficient'} days) fails to satisfy the mandatory statutory minimum 90-day advance notice requirement."
        )

    for fact in facts:
        elements.append(Paragraph(fact, body_style))

    elements.append(Spacer(1, 6))

    # Legal Grounds & Statutory Citations
    elements.append(Paragraph("<b>LEGAL GROUNDS & APPLICABLE STATUTES:</b>", bold_meta))
    if state.analysis and state.analysis.violations:
        for viol in state.analysis.violations:
            verif_badge = "(Verified Gazette)" if viol.is_verified else "(Verification Pending Gazette)"
            viol_text = f"• <b>{viol.issue}</b><br/>" \
                        f"<i>Statutory Basis:</i> {viol.statutory_basis} [Citation: {viol.kb_chunk_id}] {verif_badge}<br/>" \
                        f"{viol.summary}"
            elements.append(Paragraph(viol_text, body_style))
    else:
        elements.append(Paragraph("• Standard provisions of Karnataka Tenancy Regulations and Transfer of Property Act.", body_style))

    elements.append(Spacer(1, 6))

    # Specific Demand & Deadline
    elements.append(Paragraph("<b>SPECIFIC DEMAND & REMEDY:</b>", bold_meta))
    demand_text = (
        f"You are hereby called upon to pay and remit the full refundable balance of "
        f"<b>₹{arith.net_refundable_amount if arith else state.deposit_paid:,.0f}/-</b> directly into the Tenant's bank account "
        f"within <b>SEVEN (7) DAYS</b> of receipt of this notice, along with copies of itemised GST-compliant bills for any validly incurred repairs."
        if case_type == "deposit"
        else f"You are called upon to suspend the proposed rent enhancement until the expiry of a lawful 90-day written notice as mandated by law."
    )
    elements.append(Paragraph(demand_text, body_style))

    # Consequences of Default
    elements.append(Spacer(1, 4))
    elements.append(Paragraph("<b>CONSEQUENCES OF NON-COMPLIANCE:</b>", bold_meta))
    consequences = (
        "Please note that in the event of your failure to comply with this notice within the stipulated 7 days, "
        "the Tenant shall initiate formal proceedings before the Rent Controller / Court of Small Causes, Bengaluru, "
        "for recovery of the full sum together with interest at 12% per annum, damages for mental distress, and litigation costs, "
        "entirely at your risk and consequence."
    )
    elements.append(Paragraph(consequences, body_style))

    elements.append(Spacer(1, 20))

    # Signature Block
    sig_data = [
        [
            Paragraph("Yours sincerely,<br/><br/><br/>___________________________<br/><b>Tenant Signature</b><br/>" + tenant_name, meta_style),
            Paragraph("Copy to:<br/>1. Legal Counsel Record File<br/>2. Dispatched via Registered Post A.D.", meta_style)
        ]
    ]
    sig_table = Table(sig_data, colWidths=[250, 250])
    elements.append(sig_table)

    # Build PDF with NumberedCanvas
    doc.build(elements, canvasmaker=NumberedCanvas)
    return output_path
