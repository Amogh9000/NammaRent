from docx import Document

doc = Document('test_sample_final.docx')
texts = [p.text for p in doc.paragraphs]
print('Numbered body:', any('That I was your tenant' in t for t in texts))
sec = doc.sections[0]
h = sec.header.paragraphs
f = sec.footer.paragraphs
print('No header paragraphs with text:', all(not p.text for p in h))
print('No footer paragraphs with text:', all(not p.text for p in f))
print('Real statutes present:', any('Section 106 of the Transfer of Property Act, 1882' in t for t in texts))
print('No AI disclaimer:', not any('AI assistant' in t or 'Not legal advice' in t or 'Generated by' in t for t in texts))
print('First person present:', any('I, [TENANT NAME], residing at' in t for t in texts))
print('Yours faithfully present:', any('Yours faithfully,' in t for t in texts))
print('No FROM block at top:', not any('FROM:' in t for t in texts))
print('No copy-to line:', not any('Copy to' in t for t in texts))
